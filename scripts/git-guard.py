#!/usr/bin/env python3
"""PreToolUse lifecycle hook for Antigravity enforcing Global Git Rules #1 & #2.

Rule #1: No unconfirmed `git push` to `main` or `master` without first asking
         the user via `ask_question`.
Rule #2: Zero AI attribution (`Co-authored-by:`, `Generated by`, etc.) in commit
         messages, tags, or pull requests.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

PROTECTED_BRANCHES = frozenset({"main", "master", "refs/heads/main", "refs/heads/master"})

AI_ATTRIBUTION_PATTERNS = (
    re.compile(
        r"(?im)(?:^|[\r\n]|-m\s+[\"']?)\s*co-authored-by\s*:\s*[^\r\n]+"
    ),
    re.compile(
        r"(?i)\bco-authored-by\s*:\s*[^\r\n\"']*"
        r"(?:claude|gemini|antigravity|copilot|openai|anthropic|chatgpt|gpt|llm|\bai\b|noreply@|<[^>]+>)"
    ),
    re.compile(
        r"(?i)\bgenerated\s+(?:by|with)\s+"
        r"(?:claude|gemini|antigravity|copilot|openai|anthropic|chatgpt|gpt-?\d*|ai\b|llm\b)"
    ),
    re.compile(r"(?i)🤖\s*generated\s+with"),
)

GIT_GLOBAL_OPTS_WITH_VALUE = frozenset(
    {"-C", "-c", "--git-dir", "--work-tree", "--namespace", "--super-prefix", "--config-env"}
)

PUSH_OPTS_WITH_VALUE = frozenset(
    {"--repo", "--receive-pack", "--exec", "-o", "--push-option"}
)


def emit(decision: str, reason: str | None = None) -> None:
    payload: dict[str, Any] = {"decision": decision}
    if reason:
        payload["reason"] = reason
    sys.stdout.write(json.dumps(payload, ensure_ascii=False) + "\n")
    sys.stdout.flush()


def split_shell_segments(command_line: str) -> list[str]:
    """Split a shell command line on unquoted `;`, `|`, `&&`, `||`, or newlines."""
    segments: list[str] = []
    current: list[str] = []
    quote: str | None = None
    escaped = False
    i = 0
    n = len(command_line)

    while i < n:
        ch = command_line[i]
        if escaped:
            current.append(ch)
            escaped = False
            i += 1
            continue
        if ch == "\\":
            if quote == "'":
                current.append(ch)
            else:
                escaped = True
                current.append(ch)
            i += 1
            continue
        if quote:
            if ch == quote:
                quote = None
            current.append(ch)
            i += 1
            continue
        if ch in ("'", '"'):
            quote = ch
            current.append(ch)
            i += 1
            continue
        if ch in (";", "\n", "(", ")", "`"):
            seg = "".join(current).strip()
            if seg:
                segments.append(seg)
            current = []
            i += 1
            continue
        if ch in ("|", "&"):
            if i + 1 < n and command_line[i + 1] == ch:
                i += 2
            else:
                i += 1
            seg = "".join(current).strip()
            if seg:
                segments.append(seg)
            current = []
            continue
        current.append(ch)
        i += 1

    tail = "".join(current).strip()
    if tail:
        segments.append(tail)
    return segments


def tokenize_segment(segment: str) -> list[str]:
    try:
        tokens = shlex.split(segment, posix=True)
    except ValueError:
        tokens = segment.split()
    # Strip leading env assignments (KEY=VALUE) and common command wrappers
    idx = 0
    while idx < len(tokens):
        tok = tokens[idx]
        if "=" in tok and not tok.startswith("-") and tok.split("=", 1)[0].isidentifier():
            idx += 1
            continue
        if tok in ("env", "command", "sudo", "time", "nohup"):
            idx += 1
            continue
        break
    return tokens[idx:]


def parse_git_invocation(tokens: list[str], default_cwd: str | None) -> tuple[str | None, list[str], str | None]:
    """If tokens represent a `git` command, return (subcommand, sub_args, effective_cwd)."""
    if not tokens:
        return None, [], default_cwd
    exe = os.path.basename(tokens[0])
    if exe != "git":
        return None, [], default_cwd

    cwd = default_cwd
    i = 1
    while i < len(tokens):
        tok = tokens[i]
        if tok in GIT_GLOBAL_OPTS_WITH_VALUE:
            if tok == "-C" and i + 1 < len(tokens):
                cwd = tokens[i + 1]
            i += 2
            continue
        if any(tok.startswith(f"{opt}=") for opt in GIT_GLOBAL_OPTS_WITH_VALUE):
            if tok.startswith("-C="):
                cwd = tok.split("=", 1)[1]
            i += 1
            continue
        if tok.startswith("-C") and len(tok) > 2:
            cwd = tok[2:]
            i += 1
            continue
        if tok.startswith("-c") and len(tok) > 2:
            i += 1
            continue
        if tok.startswith("-"):
            i += 1
            continue
        return tok, tokens[i + 1 :], cwd

    return None, [], cwd


def is_ai_attribution_check_target(tokens: list[str]) -> bool:
    if not tokens:
        return False
    exe = os.path.basename(tokens[0])
    if exe == "git":
        sub, _, _ = parse_git_invocation(tokens, None)
        return sub in ("commit", "merge", "tag", "notes")
    if exe == "gh" and len(tokens) >= 3:
        return (tokens[1], tokens[2]) in (("pr", "create"), ("pr", "edit"), ("release", "create"))
    return False


def extract_message_files(tokens: list[str], cwd: str | None) -> list[str]:
    """Extract contents of any `-F`, `--file`, or `--body-file` arguments if readable."""
    contents: list[str] = []
    file_flags = {"-F", "--file", "--body-file"}
    base_dir = Path(cwd) if cwd and os.path.isdir(cwd) else Path.cwd()

    i = 0
    while i < len(tokens):
        tok = tokens[i]
        candidate: str | None = None
        if tok in file_flags and i + 1 < len(tokens):
            candidate = tokens[i + 1]
            i += 2
        elif any(tok.startswith(f"{flag}=") for flag in file_flags):
            candidate = tok.split("=", 1)[1]
            i += 1
        else:
            i += 1
            continue

        if candidate and candidate != "-":
            fpath = Path(candidate)
            if not fpath.is_absolute():
                fpath = base_dir / fpath
            if fpath.is_file():
                try:
                    contents.append(fpath.read_text(encoding="utf-8", errors="replace"))
                except OSError:
                    pass
    return contents


def has_ai_attribution(segment: str, tokens: list[str] | None = None, cwd: str | None = None) -> bool:
    if any(pattern.search(segment) for pattern in AI_ATTRIBUTION_PATTERNS):
        return True
    if tokens:
        for file_text in extract_message_files(tokens, cwd):
            if any(pattern.search(file_text) for pattern in AI_ATTRIBUTION_PATTERNS):
                return True
    return False


def get_current_branch(cwd: str | None) -> str | None:
    target_dir = cwd if cwd and os.path.isdir(cwd) else None
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=target_dir,
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
        if proc.returncode == 0:
            return proc.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    return None


def analyze_git_push(sub_args: list[str], cwd: str | None) -> tuple[bool, bool]:
    """Return (targets_protected_branch, is_force_push)."""
    if any(flag in sub_args for flag in ("--dry-run", "-n", "-h", "--help")):
        return False, False

    is_force = False
    is_all_or_mirror = False
    positional: list[str] = []

    i = 0
    while i < len(sub_args):
        arg = sub_args[i]
        if arg == "--":
            positional.extend(sub_args[i + 1 :])
            break
        if arg in PUSH_OPTS_WITH_VALUE:
            i += 2
            continue
        if any(arg.startswith(f"{opt}=") for opt in PUSH_OPTS_WITH_VALUE):
            i += 1
            continue
        if arg in ("-f", "--force", "--force-with-lease", "--force-if-includes") or arg.startswith(
            "--force-with-lease="
        ):
            is_force = True
            i += 1
            continue
        if arg in ("--all", "--mirror"):
            is_all_or_mirror = True
            i += 1
            continue
        if arg.startswith("-"):
            i += 1
            continue
        positional.append(arg)
        i += 1

    if is_all_or_mirror:
        return True, is_force

    # positional[0] is remote (if any), positional[1:] are refspecs
    if len(positional) <= 1:
        branch = get_current_branch(cwd)
        if branch in PROTECTED_BRANCHES:
            return True, is_force
        return False, is_force

    for refspec in positional[1:]:
        if refspec.startswith("+"):
            is_force = True
            refspec = refspec[1:]
        dest = refspec.split(":", 1)[-1].strip()
        if dest in PROTECTED_BRANCHES or (dest == "HEAD" and get_current_branch(cwd) in PROTECTED_BRANCHES):
            return True, is_force

    return False, is_force


def resolve_transcript_path(payload: dict[str, Any]) -> Path | None:
    candidates: list[Path] = []
    for key in ("transcriptPath", "transcript_path"):
        raw_transcript = payload.get(key)
        if isinstance(raw_transcript, str) and raw_transcript:
            candidates.append(Path(raw_transcript))
    raw_artifact = payload.get("artifactDirectoryPath")
    if isinstance(raw_artifact, str) and raw_artifact:
        candidates.append(Path(raw_artifact) / ".system_generated" / "logs" / "transcript.jsonl")

    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


def _unquote_json_str(val: Any) -> str | None:
    if not isinstance(val, str):
        return None
    if val.startswith('"') and val.endswith('"'):
        try:
            parsed = json.loads(val)
            return parsed if isinstance(parsed, str) else val
        except json.JSONDecodeError:
            return val
    return val


def _is_completed_successful_run_command(
    entries: list[dict[str, Any]], idx: int, has_generic_steps: bool
) -> bool:
    """Return True only if entries[idx] already finished with exit code 0."""
    if not has_generic_steps:
        # Synthetic unit-test transcripts without GENERIC result lines
        return True
    if idx + 1 >= len(entries):
        # Trailing PLANNER_RESPONSE with no GENERIC result yet is currently in-flight
        return False
    next_entry = entries[idx + 1]
    if next_entry.get("type") != "GENERIC":
        return False
    if next_entry.get("status") == "ERROR":
        return False
    content = next_entry.get("content")
    if isinstance(content, str) and "The command exited with code " in content:
        return "The command exited with code 0." in content
    return True


def was_ask_question_called_since_last_push(
    transcript_path: Path,
    fallback_cwd: str | None = None,
    ignore_in_flight_tail: bool = False,
) -> bool:
    """Check if `ask_question` was invoked after the most recent successful `git push` in transcript."""
    try:
        raw_lines = transcript_path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return False

    entries: list[dict[str, Any]] = []
    for line in raw_lines:
        line = line.strip()
        if not line:
            continue
        try:
            obj = json.loads(line)
            if isinstance(obj, dict):
                entries.append(obj)
        except json.JSONDecodeError:
            continue

    has_generic_steps = any(e.get("type") == "GENERIC" for e in entries)

    for idx in range(len(entries) - 1, -1, -1):
        entry = entries[idx]
        tool_calls = entry.get("tool_calls")
        if not isinstance(tool_calls, list):
            continue

        if ignore_in_flight_tail and idx == len(entries) - 1 and entry.get("type") == "PLANNER_RESPONSE":
            continue

        for tc in reversed(tool_calls):
            if not isinstance(tc, dict):
                continue
            name = tc.get("name")
            if name in ("ask_question", "AskUserQuestion"):
                return True
            if name in ("run_command", "Bash"):
                if not _is_completed_successful_run_command(entries, idx, has_generic_steps):
                    continue
                args = tc.get("args") or tc.get("input") or {}
                if not isinstance(args, dict):
                    continue
                cmd = _unquote_json_str(args.get("CommandLine") or args.get("command"))
                hist_cwd = _unquote_json_str(args.get("Cwd") or args.get("cwd")) or fallback_cwd
                if cmd:
                    for seg in split_shell_segments(cmd):
                        toks = tokenize_segment(seg)
                        sub, sub_args, eff_cwd = parse_git_invocation(toks, hist_cwd)
                        if sub == "push":
                            targets_main, _ = analyze_git_push(sub_args, eff_cwd)
                            if targets_main:
                                return False
    return False


def _extract_command_and_cwd(payload: dict[str, Any]) -> tuple[str | None, str | None]:
    """Extract (command_line, cwd) from either Antigravity (`toolCall`) or Claude Code (`tool_name`/`tool_input`)."""
    tool_call = payload.get("toolCall")
    if isinstance(tool_call, dict):
        if tool_call.get("name") != "run_command":
            return None, None
        args = tool_call.get("args") or {}
        if not isinstance(args, dict):
            return None, None
        cmd = args.get("CommandLine")
        cwd = args.get("Cwd")
        return (cmd if isinstance(cmd, str) else None), (cwd if isinstance(cwd, str) else None)

    tool_name = payload.get("tool_name")
    if tool_name == "Bash":
        tool_input = payload.get("tool_input") or {}
        if isinstance(tool_input, dict):
            cmd = tool_input.get("command")
            cwd = payload.get("cwd") or tool_input.get("cwd")
            return (cmd if isinstance(cmd, str) else None), (cwd if isinstance(cwd, str) else None)

    return None, None


def evaluate_command(payload: dict[str, Any]) -> tuple[str, str | None]:
    command_line, cwd_str = _extract_command_and_cwd(payload)
    if not isinstance(command_line, str) or not command_line.strip():
        return "allow", None

    segments = split_shell_segments(command_line)

    # 1. Check Rule #2: Zero AI attribution in commits / tags / PRs
    for segment in segments:
        tokens = tokenize_segment(segment)
        _, _, effective_cwd = parse_git_invocation(tokens, cwd_str)
        if is_ai_attribution_check_target(tokens) and has_ai_attribution(segment, tokens, effective_cwd):
            return (
                "deny",
                "[CRAFTSMAN GIT-GUARD] Blocked (Global Rule #2 — Zero AI Attribution): "
                "Commits, tags, and Pull Requests must not contain 'Co-authored-by:' or "
                "any AI attribution trailers.",
            )

    # 2. Check Rule #1: No unconfirmed push to main / master
    for segment in segments:
        tokens = tokenize_segment(segment)
        sub, sub_args, effective_cwd = parse_git_invocation(tokens, cwd_str)
        if sub != "push":
            continue
        targets_protected, is_force = analyze_git_push(sub_args, effective_cwd)
        if not targets_protected:
            continue

        if is_force:
            return (
                "force_ask",
                "[CRAFTSMAN GIT-GUARD] Detected 'git push --force' targeting a protected branch (main/master). "
                "Explicit user confirmation is required.",
            )

        transcript_path = resolve_transcript_path(payload)
        if transcript_path is None:
            return (
                "force_ask",
                "[CRAFTSMAN GIT-GUARD] Detected 'git push' targeting main/master (Global Rule #1). "
                "Please confirm this operation.",
            )

        if was_ask_question_called_since_last_push(transcript_path, effective_cwd):
            return "allow", None

        return (
            "deny",
            "[CRAFTSMAN GIT-GUARD] Blocked (Global Rule #1 — No Unconfirmed Push to main/master): "
            "Before executing 'git push' to main/master, you must first ask the user for "
            "confirmation via the 'ask_question' tool (offering a choice between pushing directly "
            "to main vs. pushing to a new feature branch for a Pull Request).",
        )

    return "allow", None


def has_recent_antigravity_approval(cwd: str | None = None) -> bool:
    """Check if any recently active Antigravity session transcript approved push via ask_question."""
    if os.environ.get("CRAFTSMAN_IGNORE_TRANSCRIPT") == "1":
        return False
    brain_dir = Path.home() / ".gemini" / "antigravity" / "brain"
    if not brain_dir.is_dir():
        return False
    now = time.time()
    recent_transcripts: list[tuple[float, Path]] = []
    for p in brain_dir.glob("*/.system_generated/logs/transcript.jsonl"):
        try:
            mtime = p.stat().st_mtime
        except OSError:
            continue
        if (now - mtime) <= 600:
            recent_transcripts.append((mtime, p))
    recent_transcripts.sort(key=lambda item: item[0], reverse=True)
    for _, transcript in recent_transcripts:
        if was_ask_question_called_since_last_push(transcript, cwd, ignore_in_flight_tail=True):
            return True
    return False


def run_native_commit_msg_hook(msg_file_str: str) -> int:
    msg_path = Path(msg_file_str)
    if not msg_path.is_file():
        return 0
    try:
        content = msg_path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return 0

    # Strip git comment lines starting with '#'
    active_lines = "\n".join(
        line for line in content.splitlines() if not line.lstrip().startswith("#")
    )
    if has_ai_attribution(active_lines):
        sys.stderr.write(
            "\n[CRAFTSMAN GIT-HOOK] Commit blocked (Global Rule #2 — Zero AI Attribution):\n"
            "Commit messages must not contain 'Co-authored-by:' or any AI attribution\n"
            "trailers (Claude, Gemini, Antigravity, Copilot, etc.).\n\n"
        )
        return 1
    return 0


def run_native_pre_push_hook() -> int:
    ref_lines = sys.stdin.read().splitlines()
    targets_protected = False
    for line in ref_lines:
        parts = line.strip().split()
        if len(parts) >= 3:
            remote_ref = parts[2]
            if remote_ref in PROTECTED_BRANCHES:
                targets_protected = True
                break

    if not targets_protected:
        return 0

    if os.environ.get("CRAFTSMAN_ALLOW_MAIN_PUSH") == "1":
        return 0

    if has_recent_antigravity_approval(os.getcwd()):
        return 0

    # If running interactively in a terminal, prompt user via /dev/tty
    if os.environ.get("CRAFTSMAN_NONINTERACTIVE") != "1":
        try:
            with open("/dev/tty", "r+", encoding="utf-8") as tty:
                tty.write(
                    "[CRAFTSMAN GIT-HOOK] Detected 'git push' targeting a protected branch (main/master). "
                    "Continue? [y/N]: "
                )
                tty.flush()
                answer = tty.readline().strip().lower()
                if answer in ("y", "yes"):
                    return 0
        except OSError:
            pass

    sys.stderr.write(
        "\n[CRAFTSMAN GIT-HOOK] Blocked direct 'git push' to main/master (Global Rule #1).\n"
        "- First ask the user for confirmation (offering a choice between a feature branch for a PR vs. direct push to main).\n"
        "- Once explicitly approved by the user, run: CRAFTSMAN_ALLOW_MAIN_PUSH=1 git push ...\n\n"
    )
    return 1


def main() -> int:
    if len(sys.argv) >= 3 and sys.argv[1] == "--git-hook":
        hook_type = sys.argv[2]
        if hook_type == "commit-msg" and len(sys.argv) >= 4:
            return run_native_commit_msg_hook(sys.argv[3])
        if hook_type == "pre-push":
            return run_native_pre_push_hook()
        return 0

    try:
        raw = sys.stdin.read()
        payload = json.loads(raw) if raw.strip() else {}
    except (OSError, json.JSONDecodeError):
        emit("allow")
        return 0

    decision, reason = evaluate_command(payload)
    emit(decision, reason)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
