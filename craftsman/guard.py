"""PreToolUse lifecycle hook and native Git hook engine enforcing Global Git Rules #1 & #2.

Rule #1: No unconfirmed `git push` to `main` or `master` (or `gh pr merge`) without first
         asking the user via `ask_question`.
Rule #2: Zero AI attribution (`Co-authored-by:`, `Generated by`, etc.) in commit
         messages, tags, or pull requests.
"""

