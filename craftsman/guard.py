SIMPLE_WRAPPERS = frozenset({"env", "command", "sudo", "time", "nohup", "nice", "stdbuf"})
TIMEOUT_OPTS_WITH_VALUE = frozenset({"-k", "-s", "--kill-after", "--signal"})
XARGS_OPTS_WITH_VALUE = frozenset({"-n", "-L", "-I", "-P", "-d", "-E", "-a", "--max-args", "--max-procs"})


def emit(decision: str, reason: str | None = None) -> None:
    payload: dict[str, Any] = {"decision": decision}
    if reason:
        payload["reason"] = reason
    sys.stdout.write(json.dumps(payload, ensure_ascii=False) + "\n")
    sys.stdout.flush()


def split_shell_segments(command_line: str) -> list[str]:
    """Split a shell command line on unquoted `;`, `|`, `&&`, `||`, subshells, or newlines, preserving heredoc bodies."""
    segments: list[str] = []
    current: list[str] = []
    quote: str | None = None
    escaped = False
    i = 0
    n = len(command_line)

    while i < n:
        ch = command_line[i]
        if escaped:
            current.append(ch)
            escaped = False
            i += 1
            continue
        if ch == "\\":
            if quote == "'":
                current.append(ch)
            else:
                escaped = True
                current.append(ch)
            i += 1
            continue
        if quote:
            if ch == quote:
                quote = None
            current.append(ch)
            i += 1
            continue
        if ch in ("'", '"'):
            quote = ch
            current.append(ch)
            i += 1
            continue
        if ch == "\n":
            seg_so_far = "".join(current)
            hd_match = HEREDOC_OPEN_RE.search(seg_so_far)
            if hd_match:
                delim = hd_match.group(1) or hd_match.group(2) or hd_match.group(3)
                current.append(ch)
                i += 1
                while i < n:
                    line_end = command_line.find("\n", i)
                    if line_end == -1:
                        line_str = command_line[i:]
                        current.append(line_str)
                        i = n
                        break
                    line_str = command_line[i : line_end + 1]
                    current.append(line_str)
                    i = line_end + 1
                    if line_str.strip() == delim:
                        break
                seg = "".join(current).strip()
                if seg:
                    segments.append(seg)
                current = []
                continue
        if ch in (";", "\n", "(", ")", "`"):
            seg = "".join(current).strip()
            if seg:
                segments.append(seg)
            current = []
            i += 1
            continue
        if ch in ("|", "&"):
            if i + 1 < n and command_line[i + 1] == ch:
                i += 2
            else:
                i += 1
            seg = "".join(current).strip()
            if seg:
                segments.append(seg)
            current = []
            continue
        current.append(ch)
        i += 1

    tail = "".join(current).strip()
    if tail:
        segments.append(tail)
    return segments


def _strip_wrappers_from_tokens(tokens: list[str]) -> list[str]:
    """Strip leading env assignments and command wrappers (`env`, `timeout`, `xargs`, etc.)."""
    idx = 0
    n = len(tokens)
    while idx < n:
        tok = tokens[idx]
        if "=" in tok and not tok.startswith("-") and tok.split("=", 1)[0].isidentifier():
            idx += 1
            continue
        exe = os.path.basename(tok)
        if exe in SIMPLE_WRAPPERS:
            idx += 1
            continue
        if exe == "timeout":
            idx += 1
            while idx < n and tokens[idx].startswith("-"):
                opt = tokens[idx]
                if opt in TIMEOUT_OPTS_WITH_VALUE:
                    idx += 2
                else:
                    idx += 1
            # Skip duration argument (e.g. '30', '10s', '5m')
            if idx < n:
                idx += 1
            continue
        if exe == "xargs":
            idx += 1
            while idx < n and tokens[idx].startswith("-"):
                opt = tokens[idx]
                if opt in XARGS_OPTS_WITH_VALUE:
                    idx += 2
                else:
                    idx += 1
            continue
        break

    # Remove shell here-string operator '<<<' so `xargs git push origin <<< main` preserves 'main'
    cleaned: list[str] = []
    for t in tokens[idx:]:
        if t == "<<<":
            continue
        # Split attached output redirection like `main>/dev/null` or `main2>/dev/null`
        redir_match = re.match(r"^([^<>]+?)(?:\d*>>?|\d*>&\d+).*$", t)
        if redir_match and redir_match.group(1):
            cleaned.append(redir_match.group(1))
        else:
            cleaned.append(t)
    return cleaned


def tokenize_segment(segment: str) -> list[str]:
    cmd_header = segment.split("\n", 1)[0]
    hd_match = HEREDOC_OPEN_RE.search(cmd_header)
    if hd_match:
        cmd_header = cmd_header[: hd_match.start()]
    try:
        tokens = shlex.split(cmd_header, posix=True)
    except ValueError:
        tokens = cmd_header.split()
    return _strip_wrappers_from_tokens(tokens)


def _extract_nested_shell_command(tokens: list[str]) -> str | None:
    """If `tokens` invoke `bash -c '...'` or `eval ...`, return the inner command string."""
    if not tokens:
        return None
    exe = os.path.basename(tokens[0])
    if exe == "eval" and len(tokens) > 1:
        return " ".join(tokens[1:])
    if exe in SHELL_EXECUTABLES:
        i = 1
        while i < len(tokens):
            tok = tokens[i]
            if tok == "-c" and i + 1 < len(tokens):
                return tokens[i + 1]
            if tok.startswith("-") and not tok.startswith("--") and "c" in tok[1:] and i + 1 < len(tokens):
                return tokens[i + 1]
            if tok.startswith("-"):
                i += 1
                continue
            break
    return None


def expand_shell_segments(command_line: str, max_depth: int = 4) -> list[str]:
    """Split a shell command line and recursively expand `sh/bash/zsh -c` and `eval` wrappers."""
    base_segments = split_shell_segments(command_line)
    if max_depth <= 0:
        return base_segments

    expanded: list[str] = []
    for seg in base_segments:
        expanded.append(seg)
        tokens = tokenize_segment(seg)
        nested = _extract_nested_shell_command(tokens)
        if nested:
            expanded.extend(expand_shell_segments(nested, max_depth=max_depth - 1))
    return expanded


def _record_git_config_alias(config_expr: str, aliases: dict[str, list[str]]) -> None:
    if "=" not in config_expr:
        return
    key, val = config_expr.split("=", 1)
    key = key.strip()
    val = val.strip()
    if key.lower().startswith("alias.") and val:
        alias_name = key[6:].strip()
        if not alias_name:
            return
        if val.startswith("!"):
            val = val[1:].strip()
            if val.startswith("git "):
                val = val[4:].strip()
        try:
            alias_tokens = shlex.split(val, posix=True)
        except ValueError:
            alias_tokens = val.split()
        if alias_tokens:
            aliases[alias_name] = alias_tokens


def parse_git_invocation(
    tokens: list[str], default_cwd: str | None
) -> tuple[str | None, list[str], str | None]:
    """If tokens represent a `git` command, return (subcommand, sub_args, effective_cwd)."""
    if not tokens:
        return None, [], default_cwd
    exe = os.path.basename(tokens[0])
    if exe != "git":
        return None, [], default_cwd

    cwd = default_cwd
    aliases: dict[str, list[str]] = {}
    i = 1
    while i < len(tokens):
        tok = tokens[i]
        if tok in GIT_GLOBAL_OPTS_WITH_VALUE:
            if tok == "-C" and i + 1 < len(tokens):
                cwd = tokens[i + 1]
            elif tok == "-c" and i + 1 < len(tokens):
                _record_git_config_alias(tokens[i + 1], aliases)
            i += 2
            continue
        if any(tok.startswith(f"{opt}=") for opt in GIT_GLOBAL_OPTS_WITH_VALUE):
            if tok.startswith("-C="):
                cwd = tok.split("=", 1)[1]
            elif tok.startswith("-c="):
                _record_git_config_alias(tok.split("=", 1)[1], aliases)
            i += 1
            continue
        if tok.startswith("-C") and len(tok) > 2:
            cwd = tok[2:]
            i += 1
            continue
        if tok.startswith("-c") and len(tok) > 2:
            _record_git_config_alias(tok[2:], aliases)
            i += 1
            continue
        if tok.startswith("-"):
            i += 1
            continue
        sub = tok
        sub_args = tokens[i + 1 :]
        if sub in aliases:
            resolved = aliases[sub]
            sub = resolved[0]
            sub_args = resolved[1:] + sub_args
        return sub, sub_args, cwd

    return None, [], cwd


def is_ai_attribution_check_target(tokens: list[str]) -> bool:
    if not tokens:
        return False
    exe = os.path.basename(tokens[0])
    if exe == "git":
        sub, _, _ = parse_git_invocation(tokens, None)
        return sub in ("commit", "merge", "tag", "notes")
    if exe == "gh" and len(tokens) >= 3:
        return (tokens[1], tokens[2]) in (("pr", "create"), ("pr", "edit"), ("release", "create"))
    return False


def is_gh_pr_merge(tokens: list[str]) -> bool:
    """Return True if tokens invoke `gh pr merge` (which merges into base branch on remote)."""
    if len(tokens) < 3:
        return False
    exe = os.path.basename(tokens[0])
    if exe != "gh" or (tokens[1], tokens[2]) != ("pr", "merge"):
        return False
    return not any(flag in tokens[3:] for flag in ("-h", "--help"))


def extract_inline_messages(tokens: list[str]) -> list[str]:
    """Extract inline message/body/trailer values from command tokens (`-m`, `--trailer`, `--body`, etc.)."""
    values: list[str] = []
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if tok in INLINE_MESSAGE_OPTS and i + 1 < len(tokens):
            values.append(tokens[i + 1])
            i += 2
            continue
        if any(tok.startswith(f"{opt}=") for opt in INLINE_MESSAGE_OPTS):
            values.append(tok.split("=", 1)[1])
            i += 1
            continue
        if (tok.startswith("-m") or tok.startswith("-b") or tok.startswith("-t")) and not tok.startswith("--") and len(tok) > 2:
            values.append(tok[2:])
            i += 1
            continue
        i += 1
    return values


def extract_message_files(tokens: list[str], cwd: str | None) -> list[str]:
    """Extract contents of any `-F`, `--file`, or `--body-file` arguments if readable."""
    contents: list[str] = []
    file_flags = {"-F", "--file", "--body-file"}
    base_dir = Path(cwd) if cwd and os.path.isdir(cwd) else Path.cwd()

    i = 0
    while i < len(tokens):
        tok = tokens[i]
        candidate: str | None = None
        if tok in file_flags and i + 1 < len(tokens):
            candidate = tokens[i + 1]
            i += 2
        elif any(tok.startswith(f"{flag}=") for flag in file_flags):
            candidate = tok.split("=", 1)[1]
            i += 1
        elif tok.startswith("-F") and len(tok) > 2:
            candidate = tok[2:]
            i += 1
        else:
            i += 1
            continue

        if candidate and candidate != "-":
            fpath = Path(candidate)
            if not fpath.is_absolute():
                fpath = base_dir / fpath
            if fpath.is_file():
                try:
                    contents.append(fpath.read_text(encoding="utf-8", errors="replace"))
                except OSError:
                    pass
    return contents


def _matches_ai_attribution_text(text: str) -> bool:
    normalized = text.replace("\\r\\n", "\n").replace("\\n", "\n").replace("\\r", "\n")
    return any(
        pattern.search(text) or pattern.search(normalized)
        for pattern in AI_ATTRIBUTION_PATTERNS
    )


def has_ai_attribution(
    segment: str, tokens: list[str] | None = None, cwd: str | None = None
) -> bool:
    if _matches_ai_attribution_text(segment):
        return True
    if tokens:
        for msg_val in extract_inline_messages(tokens):
            if _matches_ai_attribution_text(msg_val):
                return True
        for file_text in extract_message_files(tokens, cwd):
            if _matches_ai_attribution_text(file_text):
                return True
    return False


def get_current_branch(cwd: str | None) -> str | None:
    target_dir = cwd if cwd and os.path.isdir(cwd) else None
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=target_dir,
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
        if proc.returncode == 0:
            return proc.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    return None


def get_repo_toplevel(cwd: str | None) -> Path | None:
    target_dir = cwd if cwd and os.path.isdir(cwd) else None
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            cwd=target_dir,
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
        if proc.returncode == 0 and proc.stdout.strip():
            return Path(proc.stdout.strip()).resolve()
    except (OSError, subprocess.SubprocessError):
        pass
    if target_dir:
        try:
            return Path(target_dir).resolve()
        except OSError:
            return None
    return None


def analyze_git_push(sub_args: list[str], cwd: str | None) -> tuple[bool, bool]:
    """Return (targets_protected_branch, is_force_push)."""
    is_force = False
    is_all_or_mirror = False
    positional: list[str] = []

    i = 0
    while i < len(sub_args):
        arg = sub_args[i]
        if arg == "--":
            positional.extend(sub_args[i + 1 :])
            break
        if arg in PUSH_OPTS_WITH_VALUE:
            i += 2
            continue
        if any(arg.startswith(f"{opt}=") for opt in PUSH_OPTS_WITH_VALUE):
            i += 1
            continue
        if arg.startswith("-o") and len(arg) > 2:
            i += 1
            continue
        if arg in ("--dry-run", "-n", "-h", "--help"):
            return False, False
        if arg in (
            "-f",
            "--force",
            "--force-with-lease",
            "--force-if-includes",
        ) or arg.startswith("--force-with-lease="):
            is_force = True
            i += 1
            continue
        if arg in ("--all", "--mirror"):
            is_all_or_mirror = True
            i += 1
            continue
        if arg.startswith("-"):
            i += 1
            continue
        positional.append(arg)
        i += 1

    if is_all_or_mirror:
        return True, is_force

    # positional[0] is remote (if any), positional[1:] are refspecs
    if len(positional) <= 1:
        branch = get_current_branch(cwd)
        if branch in PROTECTED_BRANCHES:
            return True, is_force
        return False, is_force

    for refspec in positional[1:]:
        if refspec.startswith("+"):
            is_force = True
            refspec = refspec[1:]
        dest = refspec.split(":", 1)[-1].strip()
        if dest in PROTECTED_BRANCHES or (
            dest in ("HEAD", "@") and get_current_branch(cwd) in PROTECTED_BRANCHES
        ):
            return True, is_force

    return False, is_force


def resolve_transcript_path(payload: dict[str, Any]) -> Path | None:
    candidates: list[Path] = []
    for key in ("transcriptPath", "transcript_path"):
        raw_transcript = payload.get(key)
        if isinstance(raw_transcript, str) and raw_transcript:
            candidates.append(Path(raw_transcript).expanduser())
    raw_artifact = payload.get("artifactDirectoryPath")
    if isinstance(raw_artifact, str) and raw_artifact:
        candidates.append(
            Path(raw_artifact).expanduser() / ".system_generated" / "logs" / "transcript.jsonl"
        )

    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


def _unquote_json_str(val: Any) -> str | None:
    if not isinstance(val, str):
        return None
    if val.startswith('"') and val.endswith('"'):
        try:
            parsed = json.loads(val)
            return parsed if isinstance(parsed, str) else val
        except json.JSONDecodeError:
            return val
    return val


PUSH_ERROR_MARKERS = (
    "error: failed to push some refs",
    "fatal: The current branch",
    "fatal: Could not read from remote repository",
    "fatal: unable to access",
    "fatal: Authentication failed",
    "[CRAFTSMAN GIT-HOOK]",
)


def _has_push_error_marker(content: Any) -> bool:
    return isinstance(content, str) and any(marker in content for marker in PUSH_ERROR_MARKERS)


def _is_completed_successful_run_command(
    entries: list[dict[str, Any]], idx: int, has_generic_steps: bool
) -> bool:
    """Return True only if entries[idx] already finished with exit code 0 and no push error."""
    entry = entries[idx]
    if entry.get("status") == "ERROR" or _has_push_error_marker(entry.get("content")):
        return False
    if not has_generic_steps:
        # Synthetic unit-test transcripts without GENERIC result lines
        return True

    generic_steps: list[dict[str, Any]] = []
    scan_idx = idx + 1
    while scan_idx < len(entries) and entries[scan_idx].get("type") == "GENERIC":
        generic_steps.append(entries[scan_idx])
        scan_idx += 1

    if not generic_steps:
        # Trailing PLANNER_RESPONSE with no GENERIC result yet is currently in-flight
        return False

    for g_entry in generic_steps:
        if g_entry.get("status") == "ERROR":
            return False
        content = g_entry.get("content")
        if isinstance(content, str):
            if _has_push_error_marker(content):
                return False
            if (
                "The command exited with code " in content
                and "The command exited with code 0." not in content
            ):
                return False
    return True


def _extract_decoded_question_text(tc: dict[str, Any]) -> str:
    """Decode `questions` / `question` fields (including JSON-string-encoded arrays) into plain text."""
    args = tc.get("args") or tc.get("input")
    if not isinstance(args, dict) or not args:
        return ""

    raw_questions: Any = args.get("questions")
    if isinstance(raw_questions, str):
        try:
            raw_questions = json.loads(raw_questions)
        except json.JSONDecodeError:
            pass

    raw_single: Any = args.get("question")
    parts: list[str] = []
    if isinstance(raw_single, str) and raw_single.strip():
        parts.append(raw_single.strip())

    if isinstance(raw_questions, list):
        for item in raw_questions:
            if isinstance(item, dict):
                q_str = item.get("question")
                if isinstance(q_str, str) and q_str.strip():
                    parts.append(q_str.strip())
                opts = item.get("options")
                if isinstance(opts, list):
                    for opt in opts:
                        if isinstance(opt, str) and opt.strip():
                            parts.append(opt.strip())
            elif isinstance(item, str) and item.strip():
                parts.append(item.strip())
    elif isinstance(raw_questions, str) and raw_questions.strip():
        parts.append(raw_questions.strip())

    return "\n".join(parts)


def _is_push_confirmation_question(tc: dict[str, Any]) -> bool:
    """Return True only if `ask_question` asks about pushing/merging to a protected branch (`main`/`master`/PR)."""
    decoded_text = _extract_decoded_question_text(tc)
    if not decoded_text:
        return False
    return bool(PUSH_ACTION_RE.search(decoded_text) and PUSH_TARGET_RE.search(decoded_text))


def _is_user_response_approving_main_push(
    entries: list[dict[str, Any]], idx: int, has_generic_steps: bool
) -> bool:
    """Verify the user's answer following `entries[idx]` actually selected direct push/merge rather than a PR branch."""
    response_step_texts: list[str] = []
    scan_idx = idx + 1
    while scan_idx < len(entries) and entries[scan_idx].get("type") in ("GENERIC", "USER_INPUT"):
        raw_c = entries[scan_idx].get("content")
        if isinstance(raw_c, str) and raw_c.strip():
            response_step_texts.append(raw_c.strip())
        scan_idx += 1

    if not response_step_texts:
        # If the transcript has GENERIC steps and ask_question is the last entry, it is still unanswered
        if has_generic_steps and idx == len(entries) - 1:
            return False
        # Synthetic unit-test transcript without intermediate GENERIC response steps
        return True

    combined_resp = "\n".join(response_step_texts)
    answer_lines = [
        line.strip()
        for line in combined_resp.splitlines()
        if re.match(r"^A\d+\s*:", line.strip())
    ]
    effective_answer = "\n".join(answer_lines) if answer_lines else combined_resp

    if PR_ONLY_REJECTION_RE.search(effective_answer) and not re.search(
        r"(?i)\b(main|master)\b", effective_answer
    ):
        return False

    if DIRECT_MAIN_APPROVAL_RE.search(effective_answer):
        # Ensure it's not a PR-branch answer like "Wypchnij na gałąź release/x i utwórz Pull Request"
        if re.search(r"(?i)\b(pull\s+request|utwórz\s+pr|open\s+a\s+pr|feature\s+branch)\b", effective_answer) and not re.search(
            r"(?i)\b(main|master)\b", effective_answer
        ):
            return False
        return True

    if AFFIRMATIVE_SHORT_RE.search(effective_answer):
        return True

    return False


def _command_pushes_or_merges_protected(cmd: str, cwd: str | None) -> bool:
    """Return True if `cmd` invokes `gh pr merge` or `git push` targeting a protected branch."""
    for seg in expand_shell_segments(cmd):
        toks = tokenize_segment(seg)
        if is_gh_pr_merge(toks):
            return True
        sub, sub_args, eff_cwd = parse_git_invocation(toks, cwd)
        if sub == "push":
            targets_main, _ = analyze_git_push(sub_args, eff_cwd)
            if targets_main:
                return True
    return False


def was_ask_question_called_since_last_push(
    transcript_path: Path,
    fallback_cwd: str | None = None,
    ignore_in_flight_tail: bool = False,
) -> bool:
    """Check if an approved push-confirmation `ask_question` occurred after the most recent `git push`."""
    entries = read_transcript_entries(transcript_path)
    if not entries:
        return False

    has_generic_steps = any(e.get("type") == "GENERIC" for e in entries)
    min_idx = max(0, len(entries) - MAX_APPROVAL_STEP_DISTANCE)

    for idx in range(len(entries) - 1, min_idx - 1, -1):
        entry = entries[idx]
        tool_calls = entry.get("tool_calls")
        if not isinstance(tool_calls, list):
            continue

        if (
            ignore_in_flight_tail
            and idx == len(entries) - 1
            and entry.get("type") == "PLANNER_RESPONSE"
        ):
            continue

        for tc in reversed(tool_calls):
            if not isinstance(tc, dict):
                continue
            name = tc.get("name")
            if name in ("ask_question", "AskUserQuestion"):
                if _is_push_confirmation_question(tc) and _is_user_response_approving_main_push(
                    entries, idx, has_generic_steps
                ):
                    return True
                continue
            if name in ("run_command", "Bash"):
                if not _is_completed_successful_run_command(entries, idx, has_generic_steps):
                    continue
                args = tc.get("args") or tc.get("input") or {}
                if not isinstance(args, dict):
                    continue
                cmd = _unquote_json_str(args.get("CommandLine") or args.get("command"))
                hist_cwd = _unquote_json_str(args.get("Cwd") or args.get("cwd")) or fallback_cwd
                if cmd and _command_pushes_or_merges_protected(cmd, hist_cwd):
                    return False
    return False


def _extract_command_and_cwd(payload: dict[str, Any]) -> tuple[str | None, str | None]:
    """Extract (command_line, cwd) from either Antigravity (`toolCall`) or Claude Code (`tool_name`/`tool_input`)."""
    tool_call = payload.get("toolCall")
    if isinstance(tool_call, dict):
        if tool_call.get("name") != "run_command":
            return None, None
        args = tool_call.get("args") or {}
        if not isinstance(args, dict):
            return None, None
        cmd = args.get("CommandLine")
        cwd = args.get("Cwd")
        return (cmd if isinstance(cmd, str) else None), (cwd if isinstance(cwd, str) else None)

    tool_name = payload.get("tool_name")
    if tool_name == "Bash":
        tool_input = payload.get("tool_input") or {}
        if isinstance(tool_input, dict):
            cmd = tool_input.get("command")
            cwd = payload.get("cwd") or tool_input.get("cwd")
            return (cmd if isinstance(cmd, str) else None), (cwd if isinstance(cwd, str) else None)

    return None, None


def evaluate_command(payload: dict[str, Any]) -> tuple[str, str | None]:
    command_line, cwd_str = _extract_command_and_cwd(payload)
    if not isinstance(command_line, str) or not command_line.strip():
        return "allow", None

    segments = expand_shell_segments(command_line)

    # 1. Check Rule #2: Zero AI attribution in commits / tags / PRs
    for segment in segments:
        tokens = tokenize_segment(segment)
        _, _, effective_cwd = parse_git_invocation(tokens, cwd_str)
        if is_ai_attribution_check_target(tokens) and (
            has_ai_attribution(segment, tokens, effective_cwd)
            or (
                (
                    "<<" in command_line
                    or any(
                        t in ("-F", "--file", "--body-file")
                        or t.startswith(("-F", "--file=", "--body-file="))
                        for t in tokens
                    )
                )
                and has_ai_attribution(command_line)
            )
        ):
            return (
                "deny",
                "[CRAFTSMAN GIT-GUARD] Blocked (Global Rule #2 - Zero AI Attribution): "
                "Commits, tags, and Pull Requests must not contain 'Co-authored-by:' or "
                "any AI attribution trailers.",
            )

    # 2. Check Rule #1: No unconfirmed push to main / master (or gh pr merge)
    for segment in segments:
        tokens = tokenize_segment(segment)
        if is_gh_pr_merge(tokens):
            transcript_path = resolve_transcript_path(payload)
            if transcript_path is not None and was_ask_question_called_since_last_push(
                transcript_path, cwd_str
            ):
                return "allow", None
            return (
                "deny",
                "[CRAFTSMAN GIT-GUARD] Blocked (Global Rule #1 - No Unconfirmed Merge to Protected Branch): "
                "Before running 'gh pr merge', you must first ask the user for confirmation "
                "via the 'ask_question' tool.",
            )

        sub, sub_args, effective_cwd = parse_git_invocation(tokens, cwd_str)
        if sub != "push":
            continue
        targets_protected, is_force = analyze_git_push(sub_args, effective_cwd)
        if not targets_protected:
            continue

        if is_force:
            return (
                "force_ask",
                "[CRAFTSMAN GIT-GUARD] Detected 'git push --force' targeting a protected branch (main/master). "
                "Explicit user confirmation is required.",
            )

        transcript_path = resolve_transcript_path(payload)
        if transcript_path is None:
            return (
                "force_ask",
                "[CRAFTSMAN GIT-GUARD] Detected 'git push' targeting main/master (Global Rule #1). "
                "Please confirm this operation.",
            )

        if was_ask_question_called_since_last_push(transcript_path, effective_cwd):
            return "allow", None

        return (
            "deny",
            "[CRAFTSMAN GIT-GUARD] Blocked (Global Rule #1 - No Unconfirmed Push to main/master): "
            "Before running 'git push' to main/master, you must first ask the user for confirmation "
            "via the 'ask_question' tool (offering a choice between pushing to a feature branch "
            "for a PR vs. pushing directly to main).",
        )

    return "allow", None


def _path_belongs_to_repo(candidate_str: str, repo_root: Path) -> bool:
    try:
        resolved = Path(candidate_str).expanduser().resolve()
        return resolved == repo_root or resolved.is_relative_to(repo_root)
    except (OSError, ValueError):
        return False


def _transcript_matches_workspace(transcript_path: Path, repo_root: Path | None) -> bool:
    """Return True if the session transcript or its state file belongs to `repo_root`."""
    if repo_root is None:
        return False

    brain_conv_dir = transcript_path.parent.parent.parent
    state_file = brain_conv_dir / "craftsman_state.json"
    if state_file.is_file():
        try:
            state = json.loads(state_file.read_text(encoding="utf-8"))
            if isinstance(state, dict) and isinstance(state.get("cwd"), str):
                if _path_belongs_to_repo(state["cwd"], repo_root):
                    return True
        except (OSError, json.JSONDecodeError):
            pass

    entries = read_transcript_entries(transcript_path)
    path_keys = (
        "Cwd",
        "cwd",
        "TargetFile",
        "AbsolutePath",
        "DirectoryPath",
        "SearchPath",
        "file_path",
        "path",
    )
    for entry in entries:
        tool_calls = entry.get("tool_calls")
        if not isinstance(tool_calls, list):
            continue
        for tc in tool_calls:
            if not isinstance(tc, dict):
                continue
            args = tc.get("args") or tc.get("input")
            if not isinstance(args, dict):
                continue
            for key in path_keys:
                val = _unquote_json_str(args.get(key))
                if isinstance(val, str) and val and _path_belongs_to_repo(val, repo_root):
                    return True
    return False


def _find_recent_workspace_transcripts(cwd: str | None, max_age_sec: float = 600.0) -> list[Path]:
    brain_dir = Path.home() / ".gemini" / "antigravity" / "brain"
    if not brain_dir.is_dir():
        return []
    repo_root = get_repo_toplevel(cwd)
    if repo_root is None:
        return []
    now = time.time()
    recent: list[tuple[float, Path]] = []
    for p in brain_dir.glob("*/.system_generated/logs/transcript.jsonl"):
        try:
            mtime = p.stat().st_mtime
        except OSError:
            continue
        if (now - mtime) <= max_age_sec:
            recent.append((mtime, p))
    recent.sort(key=lambda item: item[0], reverse=True)
    return [p for _, p in recent if _transcript_matches_workspace(p, repo_root)]


def has_recent_antigravity_approval(cwd: str | None = None) -> bool:
    """Check if an active Antigravity session for this repository approved push via ask_question."""
    if os.environ.get("CRAFTSMAN_IGNORE_TRANSCRIPT") == "1":
        return False
    for transcript in _find_recent_workspace_transcripts(cwd, max_age_sec=600.0):
        if was_ask_question_called_since_last_push(transcript, cwd, ignore_in_flight_tail=True):
            return True
    return False


def _has_in_flight_agent_push(cwd: str | None = None) -> bool:
    """Return True if a very recent workspace transcript has a trailing in-flight `git push` tool call."""
    if os.environ.get("CRAFTSMAN_IGNORE_TRANSCRIPT") == "1":
        return False

    for transcript in _find_recent_workspace_transcripts(cwd, max_age_sec=60.0):
        entries = read_transcript_entries(transcript)
        if not entries:
            continue
        last_entry = entries[-1]
        if last_entry.get("type") != "PLANNER_RESPONSE":
            continue
        for tc in last_entry.get("tool_calls") or []:
            if not isinstance(tc, dict) or tc.get("name") not in ("run_command", "Bash"):
                continue
            args = tc.get("args") or tc.get("input") or {}
            if not isinstance(args, dict):
                continue
            cmd = _unquote_json_str(args.get("CommandLine") or args.get("command"))
            hist_cwd = _unquote_json_str(args.get("Cwd") or args.get("cwd")) or cwd
            if cmd and _command_pushes_or_merges_protected(cmd, hist_cwd):
                return True
    return False


def run_native_commit_msg_hook(msg_file_str: str) -> int:
    msg_path = Path(msg_file_str)
    if not msg_path.is_file():
        return 0
    try:
        content = msg_path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return 0

    # Strip everything at and below the `git commit -v` scissors line (`# --- >8 ---`)
    scissors_match = GIT_SCISSORS_RE.search(content)
    if scissors_match:
        content = content[: scissors_match.start()]

    # Strip git comment lines starting with '#'
    active_lines = "\n".join(
        line for line in content.splitlines() if not line.lstrip().startswith("#")
    )
    if has_ai_attribution(active_lines):
        sys.stderr.write(
            "\n[CRAFTSMAN GIT-HOOK] Blocked commit (Global Rule #2 - Zero AI Attribution):\n"
            "Commit messages must not contain 'Co-authored-by:' or any AI attribution trailers\n"
            "(Claude, Gemini, Antigravity, Copilot, etc.).\n\n"
        )
        return 1
    return 0


def run_native_pre_push_hook() -> int:
    ref_lines = sys.stdin.read().splitlines()
    targets_protected = False
    for line in ref_lines:
        parts = line.strip().split()
        if len(parts) >= 3:
            remote_ref = parts[2]
            if remote_ref in PROTECTED_BRANCHES:
                targets_protected = True
                break

    if not targets_protected:
        return 0

    if os.environ.get("CRAFTSMAN_ALLOW_MAIN_PUSH") == "1":
        return 0

    cwd = os.getcwd()
    if has_recent_antigravity_approval(cwd):
        return 0

    # If running interactively in a human terminal (and not an unapproved in-flight agent command), prompt via /dev/tty
    if os.environ.get("CRAFTSMAN_NONINTERACTIVE") != "1" and not _has_in_flight_agent_push(cwd):
        try:
            with (
                open("/dev/tty", "w", encoding="utf-8") as tty_out,
                open("/dev/tty", encoding="utf-8") as tty_in,
            ):
                tty_out.write(
                    "[CRAFTSMAN GIT-HOOK] Detected 'git push' to a protected branch (main/master). "
                    "Continue? [y/N]: "
                )
                tty_out.flush()
                answer = tty_in.readline().strip().lower()
                if answer in ("y", "yes", "t", "tak"):
                    return 0
        except OSError:
            pass

    sys.stderr.write(
        "\n[CRAFTSMAN GIT-HOOK] Blocked direct 'git push' to main/master (Global Rule #1).\n"
        "- Ask the user for confirmation first via 'ask_question' (offering a choice between "
        "pushing to a feature branch for a PR vs. pushing directly to main).\n"
        "- For manual terminal pushes, run interactively in a TTY to confirm at the [y/N] prompt.\n\n"
    )
    return 1


def main(argv: list[str] | None = None) -> int:
    args_list = list(sys.argv[1:] if argv is None else argv)
    if args_list and args_list[0] in ("-h", "--help"):
        print(
            "Usage: craftsman guard [--git-hook <commit-msg|pre-push> [args...]]\n\n"
            "Reads PreToolUse JSON payload from stdin when invoked without arguments,\n"
            "or executes native OS-level Git hooks when invoked with --git-hook."
        )
        return 0

    if len(args_list) >= 2 and args_list[0] == "--git-hook":
        hook_type = args_list[1]
        if hook_type == "commit-msg" and len(args_list) >= 3:
            return run_native_commit_msg_hook(args_list[2])
        if hook_type == "pre-push":
            return run_native_pre_push_hook()
        return 0

    try:
        raw = sys.stdin.read()
        loaded = json.loads(raw) if raw.strip() else {}
        payload = loaded if isinstance(loaded, dict) else {}
    except (OSError, json.JSONDecodeError):
        emit("allow")
        return 0

    decision, reason = evaluate_command(payload)
    emit(decision, reason)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
