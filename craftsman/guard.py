def emit(decision: str, reason: str | None = None) -> None:
    payload: dict[str, Any] = {"decision": decision}
    if reason:
        payload["reason"] = reason
    sys.stdout.write(json.dumps(payload, ensure_ascii=False) + "\n")
    sys.stdout.flush()


def _consume_heredoc_body(command_line: str, start: int, delim: str) -> tuple[str, int]:
    i, n = start, len(command_line)
    chunks: list[str] = []
    while i < n:
        line_end = command_line.find("\n", i)
        if line_end == -1:
            chunks.append(command_line[i:])
            return "".join(chunks), n
        line_str = command_line[i : line_end + 1]
        chunks.append(line_str)
        i = line_end + 1
        if line_str.strip() == delim:
            break
    return "".join(chunks), i


_PS_HERESTRING_OPEN_BOUNDARIES = (" ", "\t", "\n", "\r", "(", "=", ";", "|", "&")
_PS_HERESTRING_CLOSE_FOLLOWERS = (" ", "\t", "|", ";", ")", "&")


def _consume_ps_herestring_token(command_line: str, idx: int) -> tuple[str, int] | None:
    """Consume a PowerShell `@'\\n...\\n'@` or `@\"\\n...\\n\"@` here-string starting at `idx`."""
    if (
        command_line[idx] != "@"
        or (idx > 0 and command_line[idx - 1] not in _PS_HERESTRING_OPEN_BOUNDARIES)
        or idx + 2 >= len(command_line)
        or command_line[idx + 1] not in ("'", '"')
    ):
        return None
    quote_char = command_line[idx + 1]
    nl_len = 2 if command_line[idx + 2 : idx + 4] == "\r\n" else int(command_line[idx + 2] == "\n")
    if nl_len == 0:
        return None
    close_token = f"{quote_char}@"
    i, n = idx + 2 + nl_len, len(command_line)
    chunks: list[str] = []
    while i < n:
        line_end = command_line.find("\n", i)
        raw_line = command_line[i:] if line_end == -1 else command_line[i:line_end]
        clean_line = raw_line.rstrip("\r")
        if clean_line.startswith(close_token) and (
            len(clean_line) == len(close_token)
            or clean_line[len(close_token)] in _PS_HERESTRING_CLOSE_FOLLOWERS
        ):
            body = "".join(chunks).removesuffix("\n").removesuffix("\r")
            escaped_body = body.replace("'", "'\\''")
            return f"'{escaped_body}'", i + len(close_token)
        if line_end == -1:
            break
        chunks.append(command_line[i : line_end + 1])
        i = line_end + 1
    unclosed = command_line[idx + 2 + nl_len :].replace("'", "'\\''")
    return f"'{unclosed}", n


def _is_standalone_brace(command_line: str, idx: int) -> bool:
    if command_line[idx] not in ("{", "}"):
        return False
    n = len(command_line)
    sep = (" ", "\t", "\n", ";", "(", ")", "|", "&", "`")
    prev_ok = idx == 0 or command_line[idx - 1] in sep
    next_ok = idx + 1 == n or command_line[idx + 1] in sep
    return prev_ok and next_ok


def _is_redirection_ampersand(command_line: str, idx: int) -> bool:
    n = len(command_line)
    return command_line[idx] == "&" and (
        (idx > 0 and command_line[idx - 1] in (">", "<"))
        or (idx + 1 < n and command_line[idx + 1] == ">")
    )


def _flush_segment(current: list[str], events: list[str]) -> list[str]:
    seg = "".join(current).strip()
    if seg:
        events.append(seg)
    return []


def split_shell_events(command_line: str) -> list[str]:
    """Split a shell command line into command segments and subshell boundary tokens `(` and `)`."""
    events: list[str] = []
    current: list[str] = []
    quote: str | None = None
    escaped = False
    i, n = 0, len(command_line)
    while i < n:
        ch = command_line[i]
        if escaped or ch == "\\":
            escaped = (not escaped) and ch == "\\" and quote != "'"
            current.append(ch)
            i += 1
        elif quote is None and (hs := _consume_ps_herestring_token(command_line, i)) is not None:
            current.append(hs[0])
            i = hs[1]
        elif quote or ch in ("'", '"'):
            quote = None if quote == ch else (ch if quote is None else quote)
            current.append(ch)
            i += 1
        elif ch == "\n" and (hd := HEREDOC_OPEN_RE.search("".join(current))):
            delim = hd.group(1) or hd.group(2) or hd.group(3)
            body, i = _consume_heredoc_body(command_line, i + 1, delim)
            current.extend(("\n", body))
            current = _flush_segment(current, events)
        elif ch in ("(", ")"):
            current = _flush_segment(current, events)
            events.append(ch)
            i += 1
        elif ch in (";", "\n", "`") or _is_standalone_brace(command_line, i):
            current = _flush_segment(current, events)
            i += 1
        elif ch in ("|", "&") and not _is_redirection_ampersand(command_line, i):
            i += 2 if (i + 1 < n and command_line[i + 1] == ch) else 1
            current = _flush_segment(current, events)
        else:
            current.append(ch)
            i += 1
    _flush_segment(current, events)
    return events


def _strip_wrappers_from_tokens(tokens: list[str]) -> list[str]:
    """Strip leading env assignments, shell control keywords, and command wrappers (`env`, `nice`, `sudo`, `timeout`, `xargs`, etc.)."""
    idx = 0
    n = len(tokens)
    while idx < n:
        tok = tokens[idx]
        if tok in SHELL_CONTROL_KEYWORDS:
            idx += 1
            continue
        if tok == "for" and idx + 2 < n and tokens[idx + 2] == "in":
            idx += 3
            while idx < n and tokens[idx] not in ("do",):
                idx += 1
            continue
        if "=" in tok and not tok.startswith("-") and tok.split("=", 1)[0].isidentifier():
            idx += 1
            continue
        exe = os.path.basename(tok)
        if exe in SIMPLE_WRAPPERS:
            opts_with_val = WRAPPER_OPTS_WITH_VALUE.get(exe, frozenset())
            idx += 1
            while idx < n:
                cur_tok = tokens[idx]
                if cur_tok == "--":
                    idx += 1
                    break
                if (
                    "=" in cur_tok
                    and not cur_tok.startswith("-")
                    and cur_tok.split("=", 1)[0].isidentifier()
                ):
                    idx += 1
                    continue
                if cur_tok in opts_with_val:
                    idx += 2
                    continue
                if cur_tok.startswith("-"):
                    idx += 1
                    continue
                break
            continue
        if exe == "timeout":
            idx += 1
            while idx < n and tokens[idx].startswith("-"):
                opt = tokens[idx]
                if opt in TIMEOUT_OPTS_WITH_VALUE:
                    idx += 2
                else:
                    idx += 1
            # Skip duration argument (e.g. '30', '10s', '5m')
            if idx < n:
                idx += 1
            continue
        if exe == "xargs":
            idx += 1
            while idx < n and tokens[idx].startswith("-"):
                opt = tokens[idx]
                if opt in XARGS_OPTS_WITH_VALUE:
                    idx += 2
                else:
                    idx += 1
            continue
        break

    # Remove shell here-string operator '<<<' so `xargs git push origin <<< main` preserves 'main'
    return [t for t in tokens[idx:] if t != "<<<"]


def _separate_unquoted_redirections(cmd_header: str) -> str:
    """Insert spaces before unquoted redirection operators (`>/dev/null`, `2>&1`) without altering quoted strings."""
    out: list[str] = []
    quote: str | None = None
    escaped = False
    i = 0
    n = len(cmd_header)
    while i < n:
        ch = cmd_header[i]
        if escaped:
            out.append(ch)
            escaped = False
            i += 1
            continue
        if ch == "\\":
            escaped = quote != "'"
            out.append(ch)
            i += 1
            continue
        if quote:
            if ch == quote:
                quote = None
            out.append(ch)
            i += 1
            continue
        if ch in ("'", '"'):
            quote = ch
            out.append(ch)
            i += 1
            continue
        if cmd_header[i:].startswith("<<<"):
            out.append(" <<< ")
            i += 3
            continue
        # Check for unquoted redirections (`2>&1`, `&>/path`, `>/path`, `> /path`, `2>/path`, `< /path`)
        if ch in ("<", ">", "&") or ch.isdigit():
            redir_m = UNQUOTED_REDIR_RE.match(cmd_header, i)
            if redir_m and (
                not ch.isdigit()
                or i == 0
                or cmd_header[i - 1].isspace()
                or cmd_header[i - 1] in (";", "|", "&", "(")
            ):
                i = redir_m.end()
                out.append(" ")
                continue
        out.append(ch)
        i += 1
    return "".join(out)


_UNQUOTED_WIN_PATH_TOKEN_RE = re.compile(
    r"(?<!\S)(?:[A-Za-z]:|~|\.\.?|%[A-Za-z_][A-Za-z0-9_]*%|\$(?:HOME|\{HOME\}|env:[A-Za-z_][A-Za-z0-9_]*))\\[^\s\"';|&<>()]*"
)
CD_COMMANDS = frozenset({"cd", "pushd", "chdir", "set-location", "sl"})
POPD_COMMANDS = frozenset({"popd", "pop-location"})


def _preserve_unquoted_windows_backslashes(cmd_header: str) -> str:
    """Double backslashes inside unquoted Windows/tilde/env path tokens before `shlex.split(posix=True)`."""
    out: list[str] = []
    quote: str | None = None
    escaped = False
    i = 0
    n = len(cmd_header)
    while i < n:
        ch = cmd_header[i]
        if escaped:
            out.append(ch)
            escaped = False
            i += 1
            continue
        if ch in ("'", '"'):
            quote = ch if quote is None else (None if quote == ch else quote)
            out.append(ch)
            i += 1
            continue
        if quote is None:
            m = _UNQUOTED_WIN_PATH_TOKEN_RE.match(cmd_header, i)
            if m and (
                i == 0 or cmd_header[i - 1].isspace() or cmd_header[i - 1] in (";", "|", "&", "(")
            ):
                out.append(m.group(0).replace("\\", "\\\\"))
                i = m.end()
                continue
        if ch == "\\":
            escaped = quote != "'"
        out.append(ch)
        i += 1
    return "".join(out)


def _tokenize_raw_segment(segment: str) -> list[str]:
    first_line = segment.split("\n", 1)[0]
    hd_match = HEREDOC_OPEN_RE.search(first_line)
    cmd_header = first_line[: hd_match.start()] if hd_match else segment
    cmd_header = _separate_unquoted_redirections(cmd_header)
    cmd_header = _preserve_unquoted_windows_backslashes(cmd_header)
    try:
        return shlex.split(cmd_header, posix=True)
    except ValueError:
        return cmd_header.split()


def _extract_nested_shell_command(tokens: list[str], raw_segment: str = "") -> str | None:
    """If `tokens` invoke `bash -c '...'`, `bash <<EOF`, or `eval ...`, return the inner command string."""
    if not tokens:
        return None
    exe = os.path.basename(tokens[0])
    if exe == "eval" and len(tokens) > 1:
        return " ".join(tokens[1:])
    if exe in SHELL_EXECUTABLES:
        i = 1
        while i < len(tokens):
            tok = tokens[i]
            if tok == "-c" and i + 1 < len(tokens):
                return tokens[i + 1]
            if (
                tok.startswith("-")
                and not tok.startswith("--")
                and "c" in tok[1:]
                and i + 1 < len(tokens)
            ):
                return tokens[i + 1]
            if tok.startswith("-"):
                i += 1
                continue
            break
        if "\n" in raw_segment and HEREDOC_OPEN_RE.search(raw_segment.split("\n", 1)[0]):
            body = raw_segment.split("\n", 1)[1]
            body_lines = body.splitlines()
            if body_lines:
                return "\n".join(body_lines[:-1])
    return None


@dataclass(frozen=True)
class SimpleCommand:
    """A single tokenized shell segment with its effective working directory."""

    segment: str
    tokens: list[str]
    cwd: str | None


def expand_shell_path_token(raw: str) -> str:
    """Expand `~`, `$HOME`, `${HOME}`, `$env:HOME`, `$env:USERPROFILE`, and `%USERPROFILE%` in a shell argument."""
    home = str(user_home())
    expanded = re.sub(
        r"\$(?:HOME|\{HOME\}|env:USERPROFILE|env:HOME)(?=[/\\]|$)|%USERPROFILE%",
        lambda _: home,
        raw,
        flags=re.IGNORECASE,
    )
    if expanded == "~" or expanded.startswith("~/") or expanded.startswith("~\\"):
        return home + expanded[1:]
    return os.path.expanduser(expanded)


def _join_and_normpath(target: str, current_cwd: str | None) -> str:
    expanded = expand_shell_path_token(target)
    if os.sep == "/" and not re.match(r"^[A-Za-z]:[/\\]", expanded):
        expanded = expanded.replace("\\", "/")
    if os.path.isabs(expanded):
        return os.path.normpath(expanded)
    if current_cwd:
        return os.path.normpath(os.path.join(current_cwd, expanded))
    return os.path.normpath(expanded)


def _consume_wrapper_chdir_options(
    exe: str, raw_tokens: list[str], idx: int, eff_cwd: str | None
) -> tuple[int, str | None]:
    opts_with_val = WRAPPER_OPTS_WITH_VALUE.get(exe, frozenset())
    n = len(raw_tokens)
    while idx < n:
        cur_tok = raw_tokens[idx]
        if cur_tok == "--":
            return idx + 1, eff_cwd
        if "=" in cur_tok and not cur_tok.startswith("-") and cur_tok.split("=", 1)[0].isidentifier():
            idx += 1
        elif (
            (exe == "env" and cur_tok in ("-C", "--chdir"))
            or (exe == "sudo" and cur_tok in ("-D", "--chdir"))
        ) and idx + 1 < n:
            eff_cwd = _join_and_normpath(raw_tokens[idx + 1], eff_cwd)
            idx += 2
        elif exe in ("env", "sudo") and cur_tok.startswith("--chdir="):
            eff_cwd = _join_and_normpath(cur_tok.split("=", 1)[1], eff_cwd)
            idx += 1
        elif cur_tok in opts_with_val:
            idx += 2
        elif cur_tok.startswith("-"):
            idx += 1
        else:
            break
    return idx, eff_cwd


def _extract_wrapper_chdir(raw_tokens: list[str], current_cwd: str | None) -> str | None:
    """Inspect leading `env`/`sudo` wrappers for `-C`, `-D`, or `--chdir` and return the effective cwd."""
    eff_cwd = current_cwd
    idx, n = 0, len(raw_tokens)
    while idx < n:
        tok = raw_tokens[idx]
        if tok in SHELL_CONTROL_KEYWORDS:
            idx += 1
        elif tok == "for" and idx + 2 < n and raw_tokens[idx + 2] == "in":
            idx += 3
            while idx < n and raw_tokens[idx] != "do":
                idx += 1
        elif "=" in tok and not tok.startswith("-") and tok.split("=", 1)[0].isidentifier():
            idx += 1
        elif (exe := os.path.basename(tok)) in SIMPLE_WRAPPERS:
            idx, eff_cwd = _consume_wrapper_chdir_options(exe, raw_tokens, idx + 1, eff_cwd)
        else:
            break
    return eff_cwd


def _resolve_cd_target(tokens: list[str], current_cwd: str | None) -> str | None:
    """Return the updated working directory after a `cd`, `pushd`, `chdir`, or `Set-Location`/`sl` command."""
    if not tokens or tokens[0].lower() not in CD_COMMANDS:
        return current_cwd
    cmd = tokens[0].lower()
    args: list[str] = []
    idx = 1
    while idx < len(tokens):
        tok = tokens[idx]
        low = tok.lower()
        if tok == "--":
            args.extend(tokens[idx + 1 :])
            break
        if low in ("-path", "-literalpath") and idx + 1 < len(tokens):
            args.append(tokens[idx + 1])
            idx += 2
            continue
        if tok.startswith("-") and tok != "-":
            idx += 1
            continue
        args.append(tok)
        idx += 1

    if not args:
        if cmd in ("cd", "chdir", "set-location", "sl"):
            return expand_shell_path_token("~")
        return current_cwd

    target = args[0]
    if target == "-":
        return current_cwd

    return _join_and_normpath(target, current_cwd)


def _extract_find_or_fd_exec_commands(tokens: list[str]) -> list[list[str]]:
    """Extract subcommands passed to `find ... -exec/-execdir/-ok/-okdir` or `fd ... -x/--exec/-X/--exec-batch`."""
    if not tokens:
        return []
    exe = os.path.basename(tokens[0]).lower()
    subcommands: list[list[str]] = []
    if exe == "find":
        idx = 1
        n = len(tokens)
        while idx < n:
            if tokens[idx] in ("-exec", "-execdir", "-ok", "-okdir"):
                idx += 1
                sub: list[str] = []
                while idx < n and tokens[idx] not in (";", "\\;", "+"):
                    sub.append(tokens[idx])
                    idx += 1
                cleaned = _strip_wrappers_from_tokens(sub)
                if cleaned:
                    subcommands.append(cleaned)
            idx += 1
    elif exe in ("fd", "fdfind"):
        idx = 1
        n = len(tokens)
        while idx < n:
            if tokens[idx] in ("-x", "--exec", "-X", "--exec-batch"):
                idx += 1
                sub = []
                while idx < n and tokens[idx] not in (";", "\\;"):
                    sub.append(tokens[idx])
                    idx += 1
                cleaned = _strip_wrappers_from_tokens(sub)
                if cleaned:
                    subcommands.append(cleaned)
            idx += 1
    return subcommands


def _expand_nested_commands(
    tokens: list[str], seg: str, cmd_cwd: str | None, max_depth: int
) -> list[SimpleCommand]:
    if max_depth <= 0:
        return []
    out: list[SimpleCommand] = []
    nested = _extract_nested_shell_command(tokens, seg)
    if nested:
        out.extend(iter_simple_commands(nested, cwd_str=cmd_cwd, max_depth=max_depth - 1))
    for sub_tokens in _extract_find_or_fd_exec_commands(tokens):
        sub_seg = " ".join(sub_tokens)
        out.append(SimpleCommand(segment=sub_seg, tokens=sub_tokens, cwd=cmd_cwd))
        sub_nested = _extract_nested_shell_command(sub_tokens, sub_seg)
        if sub_nested:
            out.extend(iter_simple_commands(sub_nested, cwd_str=cmd_cwd, max_depth=max_depth - 1))
    return out


def iter_simple_commands(
    command_line: str, cwd_str: str | None = None, max_depth: int = 4
) -> list[SimpleCommand]:
    """Split a shell command line into tokenized segments, tracking `cd`/`pushd`/`popd`, subshell `( ... )` scope, and expanding nested shells."""
    commands: list[SimpleCommand] = []
    cur_cwd = cwd_str
    dir_stack: list[str | None] = []
    subshell_stack: list[tuple[str | None, list[str | None]]] = []

    for ev in split_shell_events(command_line):
        if ev == "(":
            subshell_stack.append((cur_cwd, list(dir_stack)))
            continue
        if ev == ")":
            if subshell_stack:
                cur_cwd, dir_stack = subshell_stack.pop()
            continue
        raw_tokens = _tokenize_raw_segment(ev)
        cmd_cwd = _extract_wrapper_chdir(raw_tokens, cur_cwd)
        tokens = _strip_wrappers_from_tokens(raw_tokens)
        commands.append(SimpleCommand(segment=ev, tokens=tokens, cwd=cmd_cwd))
        commands.extend(_expand_nested_commands(tokens, ev, cmd_cwd, max_depth))
        if tokens:
            cmd_low = tokens[0].lower()
            if cmd_low in CD_COMMANDS:
                if cmd_low == "pushd":
                    dir_stack.append(cur_cwd)
                cur_cwd = _resolve_cd_target(tokens, cur_cwd)
            elif cmd_low in POPD_COMMANDS and dir_stack:
                cur_cwd = dir_stack.pop()
    return commands


def _record_git_config_alias(config_expr: str, aliases: dict[str, list[str]]) -> None:
    if "=" not in config_expr:
        return
    key, val = config_expr.split("=", 1)
    key = key.strip()
    val = val.strip()
    if key.lower().startswith("alias.") and val:
        alias_name = key[6:].strip()
        if not alias_name:
            return
        if val.startswith("!"):
            val = val[1:].strip()
            if val.startswith("git "):
                val = val[4:].strip()
        try:
            alias_tokens = shlex.split(val, posix=True)
        except ValueError:
            alias_tokens = val.split()
        if alias_tokens:
            aliases[alias_name] = alias_tokens


def parse_git_invocation(
    tokens: list[str], default_cwd: str | None
) -> tuple[str | None, list[str], str | None]:
    """If tokens represent a `git` command, return (subcommand, sub_args, effective_cwd)."""
    if not tokens:
        return None, [], default_cwd
    exe = os.path.basename(tokens[0])
    if exe != "git":
        return None, [], default_cwd

    cwd = default_cwd
    aliases: dict[str, list[str]] = {}
    i = 1
    while i < len(tokens):
        tok = tokens[i]
        if tok in GIT_GLOBAL_OPTS_WITH_VALUE:
            if tok == "-C" and i + 1 < len(tokens):
                cwd = tokens[i + 1]
            elif tok == "-c" and i + 1 < len(tokens):
                _record_git_config_alias(tokens[i + 1], aliases)
            i += 2
            continue
        if any(tok.startswith(f"{opt}=") for opt in GIT_GLOBAL_OPTS_WITH_VALUE):
            if tok.startswith("-C="):
                cwd = tok.split("=", 1)[1]
            elif tok.startswith("-c="):
                _record_git_config_alias(tok.split("=", 1)[1], aliases)
            i += 1
            continue
        if tok.startswith("-C") and len(tok) > 2:
            cwd = tok[2:]
            i += 1
            continue
        if tok.startswith("-c") and len(tok) > 2:
            _record_git_config_alias(tok[2:], aliases)
            i += 1
            continue
        if tok.startswith("-"):
            i += 1
            continue
        sub = tok
        sub_args = tokens[i + 1 :]
        if sub in aliases:
            resolved = aliases[sub]
            sub = resolved[0]
            sub_args = resolved[1:] + sub_args
        if sub == "subtree" and sub_args and sub_args[0] == "push":
            sub = "push"
            sub_args = sub_args[1:]
        return sub, sub_args, cwd

    return None, [], cwd


ALLOWED_STASH_SUBCOMMANDS = frozenset({"list", "show", "create"})
WORKTREE_MUTATION_SUBCOMMANDS = frozenset({"reset", "checkout", "switch", "restore", "clean"})
SUBAGENT_MUTATION_SUBCOMMANDS = WORKTREE_MUTATION_SUBCOMMANDS | frozenset(
    {"commit", "merge", "rebase", "cherry-pick", "revert", "am", "apply", "pull", "rm", "mv"}
)


def find_worktree_mutation(command: str, cwd: str | None, *, subagent: bool) -> str | None:
    """Describe the first work-tree-mutating `git` invocation in `command`, or return None."""
    if not command.strip():
        return None
    blocked = SUBAGENT_MUTATION_SUBCOMMANDS if subagent else WORKTREE_MUTATION_SUBCOMMANDS
    for item in iter_simple_commands(command, cwd):
        sub, sub_args, _ = parse_git_invocation(item.tokens, item.cwd)
        if sub is None:
            continue
        if sub == "stash":
            if sub_args and sub_args[0] in ALLOWED_STASH_SUBCOMMANDS:
                continue
            action = f" {sub_args[0]}" if sub_args and not sub_args[0].startswith("-") else ""
            return f"`git stash{action}`"
        if sub in blocked:
            return f"`git {sub}`"
    return None


def _parse_gh_subcommands(tokens: list[str]) -> list[str]:
    """Extract positional subcommands from a `gh` invocation after stripping `-R`/`--repo`/`--hostname`."""
    if not tokens or os.path.basename(tokens[0]) != "gh":
        return []
    pos: list[str] = []
    i = 1
    while i < len(tokens):
        tok = tokens[i]
        if tok in ("-R", "--repo", "--hostname") and i + 1 < len(tokens):
            i += 2
            continue
        if tok.startswith(("-R", "--repo=", "--hostname=")) and len(tok) > 2:
            i += 1
            continue
        if tok.startswith("-"):
            i += 1
            continue
        pos.append(tok)
        i += 1
    return pos


def is_ai_attribution_check_target(tokens: list[str]) -> bool:
    if not tokens:
        return False
    exe = os.path.basename(tokens[0])
    if exe == "git":
        sub, _, _ = parse_git_invocation(tokens, None)
        return sub in ("commit", "merge", "tag", "notes")
    if exe == "gh":
        gh_pos = _parse_gh_subcommands(tokens)
        if len(gh_pos) >= 2:
            return (gh_pos[0], gh_pos[1]) in (
                ("pr", "create"),
                ("pr", "edit"),
                ("pr", "merge"),
                ("pr", "comment"),
                ("pr", "review"),
                ("release", "create"),
                ("release", "edit"),
                ("issue", "create"),
                ("issue", "comment"),
            )
    return False


def is_gh_pr_merge(tokens: list[str]) -> bool:
    """Return True if tokens invoke `gh pr merge` or `gh api .../pulls/.../merge`."""
    if not tokens or os.path.basename(tokens[0]) != "gh":
        return False
    if any(flag in tokens[1:] for flag in ("-h", "--help")):
        return False
    gh_pos = _parse_gh_subcommands(tokens)
    if len(gh_pos) >= 2 and (gh_pos[0], gh_pos[1]) == ("pr", "merge"):
        return True
    if gh_pos and gh_pos[0] == "api":
        joined = " ".join(tokens[1:])
        if re.search(r"pulls/\d+/merge\b", joined):
            return True
    return False


def extract_inline_messages(tokens: list[str]) -> list[str]:
    """Extract inline message/body/trailer values from command tokens (`-m`, `--trailer`, `--body`, etc.)."""
    values: list[str] = []
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if tok in INLINE_MESSAGE_OPTS and i + 1 < len(tokens):
            values.append(tokens[i + 1])
            i += 2
            continue
        if any(tok.startswith(f"{opt}=") for opt in INLINE_MESSAGE_OPTS):
            values.append(tok.split("=", 1)[1])
            i += 1
            continue
        if (
            (tok.startswith("-m") or tok.startswith("-b") or tok.startswith("-t"))
            and not tok.startswith("--")
            and len(tok) > 2
        ):
            values.append(tok[2:])
            i += 1
            continue
        i += 1
    return values


def extract_message_files(tokens: list[str], cwd: str | None) -> list[str]:
    """The contents of the files `-F`, `--file` or `--body-file` name; a file that exists but
    cannot be read is an error, so the caller cannot pass a message it did not check."""
    contents: list[str] = []
    file_flags = {"-F", "--file", "--body-file"}
    base_dir = Path(cwd) if cwd and os.path.isdir(cwd) else Path.cwd()

    i = 0
    while i < len(tokens):
        tok = tokens[i]
        candidate: str | None = None
        if tok in file_flags and i + 1 < len(tokens):
            candidate = tokens[i + 1]
            i += 2
        elif any(tok.startswith(f"{flag}=") for flag in file_flags):
            candidate = tok.split("=", 1)[1]
            i += 1
        elif tok.startswith("-F") and len(tok) > 2:
            candidate = tok[2:]
            i += 1
        else:
            i += 1
            continue

        if candidate and candidate != "-":
            fpath = Path(candidate)
            if not fpath.is_absolute():
                fpath = base_dir / fpath
            if fpath.is_file():
                contents.append(fpath.read_text(encoding="utf-8", errors="replace"))
    return contents


def _matches_ai_attribution_text(text: str) -> bool:
    normalized = text.replace("\\r\\n", "\n").replace("\\n", "\n").replace("\\r", "\n")
    candidates = (text,) if normalized == text else (text, normalized)
    for candidate in candidates:
        if any(pattern.search(candidate) for pattern in AI_ATTRIBUTION_PATTERNS):
            return True
        if AI_BOT_NAMES_RE.search(candidate):
            for match in AI_TRAILER_HEADER_RE.finditer(candidate):
                if AI_BOT_NAMES_RE.search(match.group(1)):
                    return True
    return False


def has_ai_attribution(segment: str, tokens: list[str] | None = None, cwd: str | None = None) -> bool:
    if _matches_ai_attribution_text(segment):
        return True
    if tokens:
        for msg_val in extract_inline_messages(tokens):
            if _matches_ai_attribution_text(msg_val):
                return True
        for file_text in extract_message_files(tokens, cwd):
            if _matches_ai_attribution_text(file_text):
                return True
    return False


def get_current_branch(cwd: str | None) -> str | None:
    target_dir = cwd if cwd and os.path.isdir(cwd) else None
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=target_dir,
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
        if proc.returncode == 0:
            return proc.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    return None


def get_repo_toplevel(cwd: str | None) -> Path | None:
    target_dir = cwd if cwd and os.path.isdir(cwd) else None
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            cwd=target_dir,
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
        if proc.returncode == 0 and proc.stdout.strip():
            return Path(proc.stdout.strip()).resolve()
    except (OSError, subprocess.SubprocessError):
        pass
    if target_dir:
        try:
            return Path(target_dir).resolve()
        except OSError:
            return None
    return None


def _normalize_refspec_dest(dest: str) -> str:
    cleaned = dest.strip().lower()
    cleaned = re.split(r"[~^]|@\{", cleaned, maxsplit=1)[0]
    return cleaned


def analyze_git_push(sub_args: list[str], cwd: str | None) -> tuple[bool, bool]:
    """Return (targets_protected_branch, is_force_push)."""
    is_force = False
    is_all_or_mirror = False
    is_delete = False
    positional: list[str] = []

    i = 0
    while i < len(sub_args):
        arg = sub_args[i]
        if arg == "--":
            positional.extend(sub_args[i + 1 :])
            break
        if arg in PUSH_OPTS_WITH_VALUE or arg in ("-P", "--prefix"):
            i += 2
            continue
        if any(arg.startswith(f"{opt}=") for opt in (*PUSH_OPTS_WITH_VALUE, "--prefix")):
            i += 1
            continue
        if arg.startswith("-o") and len(arg) > 2:
            i += 1
            continue
        if arg in ("--dry-run", "-n", "-h", "--help"):
            return False, False
        if arg in ("-d", "--delete"):
            is_delete = True
            i += 1
            continue
        if arg in (
            "-f",
            "--force",
            "--force-with-lease",
            "--force-if-includes",
        ) or arg.startswith("--force-with-lease="):
            is_force = True
            i += 1
            continue
        if arg in ("--all", "--mirror"):
            is_all_or_mirror = True
            i += 1
            continue
        if arg.startswith("-") and not arg.startswith("--") and len(arg) > 2:
            short_flags = arg[1:]
            if "n" in short_flags or "h" in short_flags:
                return False, False
            if "f" in short_flags:
                is_force = True
            if "d" in short_flags:
                is_delete = True
            i += 1
            continue
        if arg.startswith("-"):
            i += 1
            continue
        positional.append(arg)
        i += 1

    if is_all_or_mirror:
        return True, is_force

    # positional[0] is remote (if any), positional[1:] are refspecs
    if len(positional) <= 1:
        branch = (get_current_branch(cwd) or "").lower()
        if branch in PROTECTED_BRANCHES:
            return True, is_force
        return False, is_force

    cur_branch: str | None = None
    for refspec in positional[1:]:
        if refspec.startswith("+"):
            is_force = True
            refspec = refspec[1:]
        if refspec.startswith(":"):
            is_delete = True
        refspec_clean = re.sub(r"@\{[^}]*\}", "", refspec)
        dest = _normalize_refspec_dest(refspec_clean.split(":", 1)[-1])
        if dest in PROTECTED_BRANCHES:
            return True, (is_force or is_delete)
        if dest in ("head", "@"):
            if cur_branch is None:
                cur_branch = (get_current_branch(cwd) or "").lower()
            if cur_branch in PROTECTED_BRANCHES:
                return True, (is_force or is_delete)

    return False, is_force


def resolve_transcript_path(payload: dict[str, Any]) -> Path | None:
    candidates: list[Path] = []
    for key in ("transcriptPath", "transcript_path"):
        raw_transcript = payload.get(key)
        if isinstance(raw_transcript, str) and raw_transcript:
            candidates.append(Path(raw_transcript).expanduser())
    raw_artifact = payload.get("artifactDirectoryPath")
    if isinstance(raw_artifact, str) and raw_artifact:
        candidates.append(
            Path(raw_artifact).expanduser() / ".system_generated" / "logs" / "transcript.jsonl"
        )

    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


def _unquote_json_str(val: Any) -> str | None:
    """A string field, decoded when Antigravity wrote it as JSON text; None for anything else."""
    if not isinstance(val, str):
        return None
    decoded = decode_json_text(val)
    return decoded if isinstance(decoded, str) else val


PUSH_ERROR_MARKERS = (
    "error: failed to push some refs",
    "fatal: The current branch",
    "fatal: Could not read from remote repository",
    "fatal: unable to access",
    "fatal: Authentication failed",
    "[CRAFTSMAN GIT-HOOK]",
)


def _has_push_error_marker(content: Any) -> bool:
    return isinstance(content, str) and any(marker in content for marker in PUSH_ERROR_MARKERS)


def _is_completed_successful_run_command(
    entries: list[dict[str, Any]], idx: int, has_generic_steps: bool
) -> bool:
    """Return True only if entries[idx] already finished with exit code 0 and no push error."""
    entry = entries[idx]
    if entry.get("status") == "ERROR" or _has_push_error_marker(entry.get("content")):
        return False
    if not has_generic_steps:
        # Synthetic unit-test transcripts without GENERIC result lines
        return True

    generic_steps: list[dict[str, Any]] = []
    scan_idx = idx + 1
    while scan_idx < len(entries) and entries[scan_idx].get("type") == "GENERIC":
        generic_steps.append(entries[scan_idx])
        scan_idx += 1

    if not generic_steps:
        # Trailing PLANNER_RESPONSE with no GENERIC result yet is currently in-flight
        return False

    for g_entry in generic_steps:
        if g_entry.get("status") == "ERROR":
            return False
        content = g_entry.get("content")
        if isinstance(content, str):
            if _has_push_error_marker(content):
                return False
            if (
                "The command exited with code " in content
                and "The command exited with code 0." not in content
            ):
                return False
    return True


def _extract_individual_questions(tc: dict[str, Any]) -> list[str]:
    """Decode each question in `tc` into a list of per-question text blocks (question + options)."""
    args = tc.get("args") or tc.get("input")
    if not isinstance(args, dict) or not args:
        return []

    raw_questions: Any = args.get("questions")
    if isinstance(raw_questions, str):
        try:
            raw_questions = json.loads(raw_questions)
        except json.JSONDecodeError:
            raw_questions = None  # questions that cannot be read approve nothing

    questions: list[str] = []
    raw_single: Any = args.get("question")
    if isinstance(raw_single, str) and raw_single.strip():
        questions.append(raw_single.strip())

    if isinstance(raw_questions, list):
        for item in raw_questions:
            if isinstance(item, dict):
                q_parts: list[str] = []
                q_str = item.get("question")
                if isinstance(q_str, str) and q_str.strip():
                    q_parts.append(q_str.strip())
                opts = item.get("options")
                if isinstance(opts, list):
                    for opt in opts:
                        if isinstance(opt, dict):
                            lbl = opt.get("label")
                            if isinstance(lbl, str) and lbl.strip():
                                q_parts.append(lbl.strip())
                        elif isinstance(opt, str) and opt.strip():
                            q_parts.append(opt.strip())
                if q_parts:
                    questions.append("\n".join(q_parts))
            elif isinstance(item, str) and item.strip():
                questions.append(item.strip())
    elif isinstance(raw_questions, str) and raw_questions.strip():
        questions.append(raw_questions.strip())

    return questions


def _is_push_target_question_text(question_text: str) -> bool:
    return bool(PUSH_ACTION_RE.search(question_text) and PUSH_TARGET_RE.search(question_text))


def _is_push_confirmation_question(tc: dict[str, Any]) -> bool:
    """Return True only if `ask_question` asks about pushing/merging to a protected branch (`main`/`master`)."""
    questions = _extract_individual_questions(tc)
    return any(_is_push_target_question_text(q) for q in questions)


def _extract_user_answer_candidates(combined_resp: str) -> list[str]:
    """Extract individual user answer strings from Antigravity (`A1: ...`) or Claude (`"q"="a"`)."""
    if USER_CANCELLATION_RE.search(combined_resp):
        return []

    a_lines = [
        re.sub(r"^A\d+\s*:\s*", "", line.strip())
        for line in combined_resp.splitlines()
        if re.match(r"^A\d+\s*:", line.strip())
    ]
    if a_lines:
        return a_lines

    claude_pairs = CLAUDE_ANSWER_PAIR_RE.findall(combined_resp)
    if claude_pairs:
        return [ans.strip() for _, ans in claude_pairs if ans.strip()]

    return [combined_resp.strip()]


def _answer_rejects_direct_push(answer: str) -> bool:
    cleaned = BENIGN_NO_PR_CLARIFICATION_RE.sub(" ", answer)
    return bool(PR_BRANCH_REJECTION_RE.search(cleaned))


def _answer_approves_direct_push(answer: str) -> bool:
    cleaned = BENIGN_NO_PR_CLARIFICATION_RE.sub(" ", answer)
    if PR_BRANCH_REJECTION_RE.search(cleaned):
        return False
    return bool(DIRECT_MAIN_APPROVAL_RE.search(cleaned) or AFFIRMATIVE_SHORT_RE.search(cleaned))


def _is_user_response_approving_main_push(
    entries: list[dict[str, Any]],
    idx: int,
    has_generic_steps: bool,
    tc: dict[str, Any] | None = None,
) -> bool:
    """Verify the user's answer following `entries[idx]` actually selected direct push/merge rather than a PR branch."""
    if idx + 1 < len(entries):
        next_type = entries[idx + 1].get("type")
        if next_type in ("PLANNER_RESPONSE", "SYSTEM_MESSAGE"):
            return False

    response_step_texts: list[str] = []
    scan_idx = idx + 1
    while scan_idx < len(entries) and entries[scan_idx].get("type") in ("GENERIC", "USER_INPUT"):
        if entries[scan_idx].get("status") == "ERROR":
            return False
        raw_c = entries[scan_idx].get("content")
        if isinstance(raw_c, str) and raw_c.strip():
            response_step_texts.append(raw_c.strip())
        scan_idx += 1

    if not response_step_texts:
        if has_generic_steps and idx == len(entries) - 1:
            return False
        # Synthetic unit-test transcript with only the ask_question entry
        return idx == len(entries) - 1

    combined_resp = "\n".join(response_step_texts)
    candidates = _extract_user_answer_candidates(combined_resp)
    if not candidates:
        return False

    questions = _extract_individual_questions(tc) if tc is not None else []
    if len(questions) > 1 and len(candidates) == len(questions):
        push_answers = [
            ans
            for q, ans in zip(questions, candidates, strict=False)
            if _is_push_target_question_text(q)
        ]
        if not push_answers:
            return False
        return all(_answer_approves_direct_push(ans) for ans in push_answers)

    if any(_answer_rejects_direct_push(ans) for ans in candidates):
        return False

    return _answer_approves_direct_push(candidates[0])


def _command_pushes_or_merges_protected(cmd: str, cwd: str | None) -> bool:
    """Return True if `cmd` invokes `gh pr merge` or `git push` targeting a protected branch."""
    for item in iter_simple_commands(cmd, cwd):
        toks = item.tokens
        if is_gh_pr_merge(toks):
            return True
        sub, sub_args, eff_cwd = parse_git_invocation(toks, item.cwd)
        if sub == "push":
            targets_main, _ = analyze_git_push(sub_args, eff_cwd)
            if targets_main:
                return True
    return False


